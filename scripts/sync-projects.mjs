import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repos = [
  'python-string-similarity',
  'larkline',
  'coffer-desktop',
  'octra',
  'AutoPhraseX',
  'transformers-keras',
  'minigateway',
  'fastcart',
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'src/data/github-stats.generated.ts');
const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;

const headers = {
  Accept: 'application/vnd.github+json',
  'X-GitHub-Api-Version': '2022-11-28',
  'User-Agent': 'lost-in-orbit-project-sync',
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
};

async function fetchRepo(repo) {
  const response = await fetch(`https://api.github.com/repos/luozhouyang/${repo}`, {
    headers,
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`GitHub API ${response.status} for ${repo}: ${body.slice(0, 200)}`);
  }

  const data = await response.json();
  return {
    stars: data.stargazers_count ?? 0,
    language: data.language ?? 'Unknown',
    pushedAt: data.pushed_at ?? new Date().toISOString(),
    description: data.description ?? '',
  };
}

const stats = {};
for (const repo of repos) {
  process.stdout.write(`Fetching luozhouyang/${repo}... `);
  stats[`luozhouyang/${repo}`] = await fetchRepo(repo);
  process.stdout.write('ok\n');
}

const file = `// Generated by scripts/sync-projects.mjs. Commit the snapshot so builds stay
// deterministic and do not depend on the GitHub API.
export interface GithubStat {
  stars: number;
  language: string;
  pushedAt: string;
  description: string;
}

export const githubStats: Record<string, GithubStat> = ${JSON.stringify(stats, null, 2)};
`;

await writeFile(output, file, 'utf8');
console.log(`\nWrote ${path.relative(root, output)}`);
